from typing import Protocol
from ..contracts import IncidentPublic, ToolResult, ToolSpec, TopologySnapshot


class EvidenceBackend(Protocol):
    def capabilities(self, topology: TopologySnapshot) -> dict: ...
    def begin(self, incident: IncidentPublic) -> None: ...
    def execute(self, spec: ToolSpec) -> ToolResult: ...
    def close(self) -> None: ...
